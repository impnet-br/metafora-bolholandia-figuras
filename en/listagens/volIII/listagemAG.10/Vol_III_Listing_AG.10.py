COLS_HTML = [
    ("d", "d (dig./read)"), ("p_last", "last-digit noise"),
    ("p_block", "block noise"), ("rounds", "rounds"),
    ("recovery_rate", "recovery"),
    ("frac_wrong_unanimity", "residual failure"),
    ("refetches_per_block", "refetch/block"),
    ("refetches_per_session", "refetch/session"),
    ("worst_case_attempts", "worst case"),
]


def generate_full_html(csv_a: Path, out_html: Path, out_csv: Path):
    rows = list(csv.DictReader(csv_a.open(encoding="utf-8")))
    out_csv.write_text(csv_a.read_text(encoding="utf-8"), encoding="utf-8")

    def cell(col, v):
        if col in ("recovery_rate",):
            return f"{float(v)*100:.3f}%"
        if col in ("p_last", "p_block", "frac_wrong_unanimity",
                   "refetches_per_block", "refetches_per_session"):
            return f"{float(v):.4f}".rstrip("0").rstrip(".") or "0"
        return str(v)

    trs = []
    for r in rows:
        tds = "".join(f"<td>{html.escape(cell(c, r[c]))}</td>" for c, _ in COLS_HTML)
        trs.append(f"<tr>{tds}</tr>")
    ths = "".join(f"<th>{html.escape(t)}</th>" for _, t in COLS_HTML)
    body = f"""<div class="wrap">
<h1>SZM &mdash; Monte Carlo simulation (full table)</h1>
<p class="sub">Feasibility study of the Successive Zooms Method.
{len(rows)} configurations &middot; 20 000 sessions each &middot; precision 20 digits.</p>
<div class="card">
<b>How to read.</b> Three noisy devices read each block; if they disagree, the
monitor orders a reprocess until there is unanimity. The value is recovered
almost always &mdash; the <i>residual failure</i> is the rare <i>wrong unanimity</i>
(the three agree on the same wrong value), which the majority-of-3 does not
detect. <code>d</code> is the number of digits read per round; more digits =
fewer rounds, at the cost of a more expensive device.
</div>
<div class="card">
<b>Downloads.</b> The full grid and the three programs that produce it:
<p style="margin:10px 0 0">
<a class="btn" href="montecarlo_full.csv" download>Full table (CSV)</a>
<a class="btn" href="../../listagens/volIII/listagemAG.8/">Simulator (Listing AG.8)</a>
<a class="btn" href="../../listagens/volIII/listagemAG.9/">Sweeper (Listing AG.9)</a>
<a class="btn" href="../../listagens/volIII/listagemAG.10/">Formatter (Listing AG.10)</a>
</p>
<p class="sub" style="margin:10px 0 0">The simulator and the sweeper generate the data; the
formatter produces this table and the book's compact version. Fixed seeds
&mdash; whoever runs it gets exactly these numbers.</p>
</div>
<div class="card scroll"><table><thead><tr>{ths}</tr></thead>
<tbody>{''.join(trs)}</tbody></table></div>
<footer>Generated by <code>format_tables_szm.py</code> from the simulator
<code>szm_feasibility.py</code>. Fixed seeds &mdash; reproducible results.
<a href="https://github.com/impnet-br/metafora-bolholandia-figuras">Repository</a>.
</footer></div>"""
    doc = ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
           '<meta name="viewport" content="width=device-width,initial-scale=1">'
           '<title>SZM &mdash; full Monte Carlo</title>'
           f'<style>{CSS}</style></head><body>{body}</body></html>')
    out_html.write_text(doc, encoding="utf-8")
    print(f"  {out_html.name}: {len(rows)} rows + CSV")


def main():
    print("Formatting:")
    generate_compact_latex(SP / "feas_study_B_book.csv",
                           SP / "tab_montecarlo_compact.tex")
    generate_full_html(SP / "feas_study_A_full.csv",
                       SP / "montecarlo_full.html",
                       SP / "montecarlo_full.csv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
