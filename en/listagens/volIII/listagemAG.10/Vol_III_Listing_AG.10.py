# -*- coding: utf-8 -*-
"""Formats the SZM feasibility results into two outputs:

  (1) tab_montecarlo_compact.tex  -- compact table for the BOOK (Study B),
      from the terrible device to the cheap three-and-a-half-digit one,
      showing the cost knee.
  (2) montecarlo_full.html + .csv -- the full grid (Study A) for electronic
      publication (GitHub + QR).

It is the "formatter code" that accompanies the POC. It reads the CSVs
generated by sweep_feasibility.py; it does not run the simulation.
"""
import csv
import html
import sys
from pathlib import Path

SP = Path(__file__).parent

# labels for the Study B rows (book), in CSV order
LABELS_B = {
    (2, 0.1, 0.01):     ("Terrible",                False),
    (2, 0.05, 0.005):   ("Poor",                     False),
    (2, 0.02, 0.0001):  ("Reasonable (2 digits)",   False),
    (3, 0.02, 0.0001):  ("\\textbf{Cheap: 3\\textonehalf\\ digits}", True),
    (4, 0.02, 0.0001):  ("4 digits",                False),
    (3, 0.01, 0.0001):  ("3\\textonehalf\\ digits, less noise", False),
}


def f2(x):
    return f"{float(x):.2f}"


def pct(x):
    return f"{float(x)*100:.3f}\\,\\%"


def pct_noise(x):
    # last-digit noise: an integer, as in the book's table
    return f"{round(float(x)*100)}\\,\\%"


# ---------------------------------------------------------------- BOOK (B)
def generate_compact_latex(csv_b: Path, out: Path):
    rows = list(csv.DictReader(csv_b.open(encoding="utf-8")))
    L = []
    L.append("% Generated by format_tables_szm.py -- do not edit by hand.")
    L.append("% Compact table (Study B). The full grid (Study A) is published")
    L.append("% at .../tabelas/montecarlo/, alongside this listing.")
    L.append("\\begin{table}[H]")
    L.append("\\centering")
    L.append("\\caption{Feasibility of the SZM by device quality (prec.\\ 20, "
             "20,000 sessions per scenario, three devices with a unanimity "
             "protocol that \\emph{reprocesses until success}). The value is "
             "always recovered, except for the extremely rare \\emph{unanimous "
             "error} (the three devices agree on the \\emph{same} incorrect "
             "value): hence the recovery rate of 99.99\\,\\% rather than "
             "100\\,\\%. The recommended operating point (green) is a cheap "
             "3\\textonehalf-digit device: it recovers with negligible "
             "reprocessing and in fewer rounds than a 2-digit one. Going up to "
             "4 digits saves only two rounds, without justifying the cost.}")
    L.append("\\label{tab:montecarlo}")
    L.append("\\small")
    L.append("\\setlength{\\tabcolsep}{5pt}")
    L.append("\\renewcommand{\\arraystretch}{1.2}")
    L.append("\\begin{tabular}{@{}lccccc@{}}")
    L.append("\\toprule")
    L.append("Scenario & \\makecell{d\\\\(dig./read)} & "
             "\\makecell{noise on\\\\last digit} & rounds & "
             "\\makecell{recovery\\\\rate} & "
             "\\makecell{reproc.\\\\per block} \\\\")
    L.append("\\midrule")
    for r in rows:
        key = (int(r["d"]), float(r["p_last"]), float(r["p_block"]))
        label, highlight = LABELS_B.get(key, (f"d={r['d']}", False))
        line = (f"{label} & {r['d']} & {pct_noise(r['p_last'])} & {r['rounds']} & "
                f"{pct(r['recovery_rate'])} & {f2(r['refetches_per_block'])}")
        if highlight:
            line = "\\rowcolor{green!12}\n" + line
        L.append(line + " \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    L.append("\\end{table}")
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"  {out.name}: {len(rows)} rows")


